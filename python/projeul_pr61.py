from collections import defaultdict

problem = """Problem 61: Cyclical Figurate Numbers

Triangle, square, pentagonal, hexagonal, heptagonal, and octagonal numbers
are all figurate (polygonal) numbers and are generated by the following
formulae:
                    Triangle:   P(3,n) = n(n+1)/2
                    Square:     P(4,n) = n^2
                    Pentagonal: P(5,n) = n(3n-1)/2
                    Hexagonal:  P(6,n) = n(2n-1)
                    Heptagonal: P(7,n) = n(5n-3)/2
                    Octagonal:  P(8,n) = n(3n-2)

The ordered set of three 4-digit numbers: 8128, 2882, 8281, has three
interesting properties:

1. The set is cyclic, in that the last two digits of each number are the
   first two digits of the next, including the last number with the first.
2. Each polygonal type: triangle (P(3,127)=8128), square (P(4,91)=8281),
   and pentagonal (P(5,44)=2882), is represented by a different number in
   the set.
3. This is the only set of 4-digit numbers with this property.

Find the sum of the only ordered set of six cyclic 4-digit numbers for
which each polygonal type: triangle, square, pentagonal, hexagonal,
heptagonal, and octagonal, is represented by a different number in the
set.
"""

prefix = lambda n: n // 100
suffix = lambda n: n % 100


polygonal = lambda t, n: [
    n * (n + 1) // 2,
    n * n,
    n * (3 * n - 1) // 2,
    n * (2 * n - 1),
    n * (5 * n - 3) // 2,
    n * (3 * n - 2),
][t-3]


def generate_polygonal_numbers(type: int) -> list[int]:
    numbers = []
    n = 1

    while True:
        num = polygonal(type, n)

        if num > 9999:
            break

        if num >= 1000 and num % 100 >= 10:
            numbers.append(num)

        n += 1

    return numbers


def index_by_prefix(numbers: list[int]) -> dict[int, list[int]]:
    index = defaultdict(list)

    for num in numbers:
        index[prefix(num)].append(num)

    return index


def search(types: list[int]) -> list[list[int]]:
    polygonal_numbers = {
        t: generate_polygonal_numbers(t)
        for t in types
    }

    prefix_indexes = {
        t: index_by_prefix(numbers)
        for t,numbers in polygonal_numbers.items()
    }

    def _search(path: list[int], used_types: list[int]) -> list[int]:
        if len(path) == len(types):
            return path \
                if suffix(path[-1]) == prefix(path[0]) \
                else []

        for t in types:
            if t in used_types:
                continue

            prefixes_from_suffix = prefix_indexes[t].get(suffix(path[-1]), [])
            for num in prefixes_from_suffix:
                result = _search(
                    path + [num],
                    used_types + [t],
                )

                if result:
                    return result

        return []

    results = []
    for num in polygonal_numbers[types[-1]]:
        search_result = _search([num], [types[-1]])
        if search_result:
            results.append(search_result)

    return results


print(problem)

for i in range(3,9):
    types = list(range(3, i+1))
    print(f"All the cyclic 4-digit polygonal numbers of type {', '.join(str(t) for t in types)} are:")
    print("\n".join([str(l) for l in search(types)]))
    print()

print("Answer:", sum(search([3,4,5,6,7,8])[0]))